-- FYIP Terminal baseline schema for Netlify Database (PostgreSQL).
-- Mirrors the SQLite schema used by the local workstation build.

CREATE TABLE IF NOT EXISTS users (
  id            TEXT PRIMARY KEY,
  email         TEXT NOT NULL UNIQUE,
  display_name  TEXT NOT NULL,
  password_hash TEXT NOT NULL,
  status        TEXT NOT NULL DEFAULT 'active',
  created_at    TEXT NOT NULL,
  updated_at    TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS roles (
  id          TEXT PRIMARY KEY,
  key         TEXT NOT NULL UNIQUE,
  name        TEXT NOT NULL,
  description TEXT
);

CREATE TABLE IF NOT EXISTS user_roles (
  user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  role_id TEXT NOT NULL REFERENCES roles(id) ON DELETE CASCADE,
  PRIMARY KEY (user_id, role_id)
);

CREATE TABLE IF NOT EXISTS exchanges (
  id       TEXT PRIMARY KEY,
  code     TEXT NOT NULL UNIQUE,
  name     TEXT NOT NULL,
  timezone TEXT NOT NULL,
  country  TEXT
);

CREATE TABLE IF NOT EXISTS instruments (
  id                  TEXT PRIMARY KEY,
  symbol              TEXT NOT NULL,
  display_name        TEXT NOT NULL,
  asset_class         TEXT NOT NULL,
  exchange_id         TEXT REFERENCES exchanges(id),
  currency            TEXT NOT NULL,
  price_scale         INTEGER NOT NULL DEFAULT 2,
  tick_size           DOUBLE PRECISION NOT NULL DEFAULT 0.01,
  contract_multiplier DOUBLE PRECISION NOT NULL DEFAULT 1,
  expiration          TEXT,
  futures_month       TEXT,
  futures_year        INTEGER,
  is_continuous       INTEGER NOT NULL DEFAULT 0,
  roll_methodology    TEXT,
  underlying_id       TEXT REFERENCES instruments(id),
  underlying_kind     TEXT,
  timezone            TEXT NOT NULL DEFAULT 'America/New_York',
  status              TEXT NOT NULL DEFAULT 'active',
  deep_link           TEXT,
  created_at          TEXT NOT NULL,
  updated_at          TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_instruments_class ON instruments(asset_class);
CREATE INDEX IF NOT EXISTS idx_instruments_symbol ON instruments(symbol);
CREATE INDEX IF NOT EXISTS idx_instruments_underlying ON instruments(underlying_id);

CREATE TABLE IF NOT EXISTS trading_sessions (
  id           TEXT PRIMARY KEY,
  exchange_id  TEXT NOT NULL REFERENCES exchanges(id) ON DELETE CASCADE,
  name         TEXT NOT NULL,
  open_local   TEXT NOT NULL,
  close_local  TEXT NOT NULL,
  session_type TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS instrument_mappings (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  instrument_id   TEXT NOT NULL REFERENCES instruments(id) ON DELETE CASCADE,
  provider        TEXT NOT NULL,
  provider_symbol TEXT NOT NULL,
  entitlement     TEXT,
  UNIQUE (provider, provider_symbol)
);
CREATE INDEX IF NOT EXISTS idx_mappings_instrument ON instrument_mappings(instrument_id);

CREATE TABLE IF NOT EXISTS sessions (
  id         TEXT PRIMARY KEY,
  user_id    TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  issued_at  TEXT NOT NULL,
  expires_at TEXT NOT NULL,
  revoked_at TEXT,
  user_agent TEXT,
  ip         TEXT
);
CREATE INDEX IF NOT EXISTS idx_sessions_user ON sessions(user_id);

CREATE TABLE IF NOT EXISTS audit_logs (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  at          TEXT NOT NULL,
  actor_id    TEXT,
  actor_email TEXT,
  action      TEXT NOT NULL,
  target      TEXT,
  status      TEXT NOT NULL,
  detail      TEXT,
  ip          TEXT
);
CREATE INDEX IF NOT EXISTS idx_audit_at ON audit_logs(at DESC);
CREATE INDEX IF NOT EXISTS idx_audit_action ON audit_logs(action);

CREATE TABLE IF NOT EXISTS alerts (
  id            TEXT PRIMARY KEY,
  user_id       TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  name          TEXT NOT NULL,
  kind          TEXT NOT NULL,
  target        TEXT,
  condition     TEXT NOT NULL,
  delivery      TEXT NOT NULL DEFAULT 'in_app',
  enabled       INTEGER NOT NULL DEFAULT 1,
  state         TEXT NOT NULL DEFAULT 'idle',
  last_fired_at TEXT,
  created_at    TEXT NOT NULL,
  updated_at    TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_alerts_user ON alerts(user_id);

CREATE TABLE IF NOT EXISTS alert_events (
  id       TEXT PRIMARY KEY,
  alert_id TEXT NOT NULL REFERENCES alerts(id) ON DELETE CASCADE,
  fired_at TEXT NOT NULL,
  message  TEXT NOT NULL,
  payload  TEXT,
  source   TEXT
);
CREATE INDEX IF NOT EXISTS idx_alert_events_alert ON alert_events(alert_id, fired_at DESC);

CREATE TABLE IF NOT EXISTS bot_connections (
  id             TEXT PRIMARY KEY,
  user_id        TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  label          TEXT NOT NULL,
  platform       TEXT NOT NULL,
  strategy       TEXT,
  version        TEXT,
  enabled        INTEGER NOT NULL DEFAULT 0,
  exec_enabled   INTEGER NOT NULL DEFAULT 0,
  last_heartbeat TEXT,
  state          TEXT NOT NULL DEFAULT 'unknown',
  metadata       TEXT,
  created_at     TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS bot_events (
  id         TEXT PRIMARY KEY,
  bot_id     TEXT NOT NULL REFERENCES bot_connections(id) ON DELETE CASCADE,
  at         TEXT NOT NULL,
  level      TEXT NOT NULL,
  event_type TEXT NOT NULL,
  message    TEXT NOT NULL,
  payload    TEXT
);
CREATE INDEX IF NOT EXISTS idx_bot_events_bot ON bot_events(bot_id, at DESC);

CREATE TABLE IF NOT EXISTS bridge_installations (
  id               TEXT PRIMARY KEY,
  label            TEXT NOT NULL,
  platform         TEXT NOT NULL,
  token_hash       TEXT NOT NULL,
  last_heartbeat   TEXT,
  connection_state TEXT NOT NULL DEFAULT 'disconnected',
  capabilities     TEXT,
  version          TEXT,
  created_at       TEXT NOT NULL,
  revoked_at       TEXT
);

CREATE TABLE IF NOT EXISTS data_provider_configs (
  id           TEXT PRIMARY KEY,
  provider_key TEXT NOT NULL UNIQUE,
  kind         TEXT NOT NULL,
  enabled      INTEGER NOT NULL DEFAULT 0,
  entitlement  TEXT,
  notes        TEXT,
  updated_at   TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS quote_snapshots (
  instrument_id      TEXT NOT NULL REFERENCES instruments(id) ON DELETE CASCADE,
  provider           TEXT NOT NULL,
  provider_symbol    TEXT,
  exchange           TEXT,
  bid                DOUBLE PRECISION,
  ask                DOUBLE PRECISION,
  last               DOUBLE PRECISION,
  open               DOUBLE PRECISION,
  high               DOUBLE PRECISION,
  low                DOUBLE PRECISION,
  prev_close         DOUBLE PRECISION,
  volume             DOUBLE PRECISION,
  open_interest      DOUBLE PRECISION,
  data_status        TEXT NOT NULL DEFAULT 'unavailable',
  entitlement        TEXT,
  event_timestamp    TEXT,
  received_timestamp TEXT NOT NULL,
  updated_at         TEXT NOT NULL,
  PRIMARY KEY (instrument_id, provider)
);

CREATE TABLE IF NOT EXISTS trade_prints (
  id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  instrument_id      TEXT NOT NULL,
  provider           TEXT NOT NULL,
  provider_symbol    TEXT,
  price              DOUBLE PRECISION NOT NULL,
  size               DOUBLE PRECISION NOT NULL,
  side               TEXT,
  side_source        TEXT NOT NULL DEFAULT 'unknown',
  event_timestamp    TEXT NOT NULL,
  received_timestamp TEXT NOT NULL,
  data_status        TEXT NOT NULL,
  sequence           DOUBLE PRECISION
);
CREATE INDEX IF NOT EXISTS idx_trade_prints_instrument_time ON trade_prints(instrument_id, event_timestamp);
CREATE INDEX IF NOT EXISTS idx_trade_prints_time ON trade_prints(event_timestamp);

CREATE TABLE IF NOT EXISTS depth_snapshots (
  id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  instrument_id      TEXT NOT NULL,
  provider           TEXT NOT NULL,
  provider_symbol    TEXT,
  event_timestamp    TEXT NOT NULL,
  received_timestamp TEXT NOT NULL,
  bids               TEXT NOT NULL,
  asks               TEXT NOT NULL,
  data_status        TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_depth_snapshots_instrument_time ON depth_snapshots(instrument_id, event_timestamp);
CREATE INDEX IF NOT EXISTS idx_depth_snapshots_time ON depth_snapshots(event_timestamp);

CREATE TABLE IF NOT EXISTS futures_minute_volume (
  instrument_id TEXT NOT NULL,
  minute        TEXT NOT NULL,
  price         DOUBLE PRECISION NOT NULL,
  volume        DOUBLE PRECISION NOT NULL,
  buy_volume    DOUBLE PRECISION NOT NULL,
  sell_volume   DOUBLE PRECISION NOT NULL,
  prints        INTEGER NOT NULL,
  price_volume  DOUBLE PRECISION NOT NULL,
  PRIMARY KEY (instrument_id, minute, price)
);
CREATE INDEX IF NOT EXISTS idx_fmv_minute ON futures_minute_volume(minute);

CREATE TABLE IF NOT EXISTS news_sources (
  id       TEXT PRIMARY KEY,
  key      TEXT NOT NULL UNIQUE,
  name     TEXT NOT NULL,
  kind     TEXT NOT NULL,
  homepage TEXT,
  licensed INTEGER NOT NULL DEFAULT 0,
  enabled  INTEGER NOT NULL DEFAULT 0,
  notes    TEXT
);

CREATE TABLE IF NOT EXISTS news_items (
  id            TEXT PRIMARY KEY,
  source_key    TEXT NOT NULL,
  headline      TEXT NOT NULL,
  summary       TEXT,
  url           TEXT,
  priority      TEXT NOT NULL DEFAULT 'general',
  priority_rule TEXT,
  categories    TEXT,
  instruments   TEXT,
  published_at  TEXT NOT NULL,
  received_at   TEXT NOT NULL,
  ingested_via  TEXT NOT NULL,
  is_fixture    INTEGER NOT NULL DEFAULT 0,
  dedupe_key    TEXT,
  UNIQUE (source_key, dedupe_key)
);
CREATE INDEX IF NOT EXISTS idx_news_published ON news_items(published_at DESC);
CREATE INDEX IF NOT EXISTS idx_news_priority ON news_items(priority);

CREATE TABLE IF NOT EXISTS company_profiles (
  instrument_id   TEXT PRIMARY KEY REFERENCES instruments(id) ON DELETE CASCADE,
  legal_name      TEXT NOT NULL,
  sector          TEXT,
  industry        TEXT,
  country         TEXT,
  employees       INTEGER,
  description     TEXT,
  cik             TEXT,
  fiscal_year_end TEXT,
  source          TEXT,
  updated_at      TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS company_financials (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  instrument_id TEXT NOT NULL REFERENCES instruments(id) ON DELETE CASCADE,
  statement     TEXT NOT NULL,
  line_item     TEXT NOT NULL,
  period        TEXT NOT NULL,
  period_type   TEXT NOT NULL,
  value         DOUBLE PRECISION,
  unit          TEXT,
  currency      TEXT,
  source        TEXT NOT NULL,
  filed_at      TEXT,
  UNIQUE (instrument_id, statement, line_item, period)
);

CREATE TABLE IF NOT EXISTS filings (
  id            TEXT PRIMARY KEY,
  instrument_id TEXT NOT NULL REFERENCES instruments(id) ON DELETE CASCADE,
  form_type     TEXT NOT NULL,
  title         TEXT,
  filed_at      TEXT NOT NULL,
  period        TEXT,
  url           TEXT,
  accession     TEXT,
  source        TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_filings_instrument ON filings(instrument_id, filed_at DESC);

CREATE TABLE IF NOT EXISTS economic_events (
  id           TEXT PRIMARY KEY,
  country      TEXT NOT NULL,
  indicator    TEXT NOT NULL,
  importance   TEXT NOT NULL,
  scheduled_at TEXT NOT NULL,
  timezone     TEXT NOT NULL DEFAULT 'UTC',
  unit         TEXT,
  source       TEXT NOT NULL,
  source_url   TEXT,
  status       TEXT NOT NULL DEFAULT 'scheduled',
  is_fixture   INTEGER NOT NULL DEFAULT 0,
  created_at   TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_econ_scheduled ON economic_events(scheduled_at);

CREATE TABLE IF NOT EXISTS economic_observations (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id         TEXT REFERENCES economic_events(id) ON DELETE SET NULL,
  country          TEXT NOT NULL,
  indicator        TEXT NOT NULL,
  period           TEXT,
  actual           DOUBLE PRECISION,
  consensus        DOUBLE PRECISION,
  previous         DOUBLE PRECISION,
  revised_previous DOUBLE PRECISION,
  unit             TEXT,
  source           TEXT NOT NULL,
  source_url       TEXT,
  is_fixture       INTEGER NOT NULL DEFAULT 0,
  published_at     TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_econ_obs_indicator ON economic_observations(country, indicator, published_at);

CREATE TABLE IF NOT EXISTS options_snapshots (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  underlying_id    TEXT NOT NULL REFERENCES instruments(id) ON DELETE CASCADE,
  as_of            TEXT NOT NULL,
  expiration       TEXT NOT NULL,
  strike           DOUBLE PRECISION NOT NULL,
  option_type      TEXT NOT NULL,
  bid              DOUBLE PRECISION,
  ask              DOUBLE PRECISION,
  last             DOUBLE PRECISION,
  volume           DOUBLE PRECISION,
  open_interest    DOUBLE PRECISION,
  implied_vol      DOUBLE PRECISION,
  delta            DOUBLE PRECISION,
  gamma            DOUBLE PRECISION,
  theta            DOUBLE PRECISION,
  vega             DOUBLE PRECISION,
  rho              DOUBLE PRECISION,
  greeks_source    TEXT NOT NULL,
  underlying_price DOUBLE PRECISION,
  source           TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_opts_underlying ON options_snapshots(underlying_id, as_of DESC);

CREATE TABLE IF NOT EXISTS saved_charts (
  id            TEXT PRIMARY KEY,
  user_id       TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  instrument_id TEXT REFERENCES instruments(id),
  title         TEXT NOT NULL,
  timeframe     TEXT NOT NULL,
  study         TEXT,
  template      TEXT,
  created_at    TEXT NOT NULL,
  updated_at    TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS chart_annotations (
  id         TEXT PRIMARY KEY,
  chart_id   TEXT NOT NULL REFERENCES saved_charts(id) ON DELETE CASCADE,
  kind       TEXT NOT NULL,
  payload    TEXT NOT NULL,
  created_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS workspaces (
  id         TEXT PRIMARY KEY,
  user_id    TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  name       TEXT NOT NULL,
  is_default INTEGER NOT NULL DEFAULT 0,
  layout     TEXT NOT NULL,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_workspaces_user ON workspaces(user_id);

CREATE TABLE IF NOT EXISTS workspace_panels (
  id                   TEXT PRIMARY KEY,
  workspace_id         TEXT NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
  module_key           TEXT NOT NULL,
  position             INTEGER NOT NULL,
  config               TEXT,
  linked_instrument_id TEXT
);

CREATE TABLE IF NOT EXISTS watchlists (
  id         TEXT PRIMARY KEY,
  user_id    TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  name       TEXT NOT NULL,
  is_default INTEGER NOT NULL DEFAULT 0,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_watchlists_user ON watchlists(user_id);

CREATE TABLE IF NOT EXISTS watchlist_items (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  watchlist_id  TEXT NOT NULL REFERENCES watchlists(id) ON DELETE CASCADE,
  instrument_id TEXT NOT NULL REFERENCES instruments(id) ON DELETE CASCADE,
  sort_order    INTEGER NOT NULL DEFAULT 0,
  UNIQUE (watchlist_id, instrument_id)
);

CREATE TABLE IF NOT EXISTS portfolio_accounts (
  id            TEXT PRIMARY KEY,
  user_id       TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  label         TEXT NOT NULL,
  broker        TEXT NOT NULL,
  account_ref   TEXT NOT NULL,
  base_currency TEXT NOT NULL DEFAULT 'USD',
  mode          TEXT NOT NULL DEFAULT 'read_only',
  created_at    TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_port_accounts_user ON portfolio_accounts(user_id);

CREATE TABLE IF NOT EXISTS positions (
  id            TEXT PRIMARY KEY,
  account_id    TEXT NOT NULL REFERENCES portfolio_accounts(id) ON DELETE CASCADE,
  instrument_id TEXT NOT NULL REFERENCES instruments(id),
  quantity      DOUBLE PRECISION NOT NULL,
  avg_price     DOUBLE PRECISION NOT NULL,
  opened_at     TEXT NOT NULL,
  updated_at    TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_positions_account ON positions(account_id);

CREATE TABLE IF NOT EXISTS trades (
  id            TEXT PRIMARY KEY,
  account_id    TEXT NOT NULL REFERENCES portfolio_accounts(id) ON DELETE CASCADE,
  instrument_id TEXT NOT NULL REFERENCES instruments(id),
  side          TEXT NOT NULL,
  quantity      DOUBLE PRECISION NOT NULL,
  price         DOUBLE PRECISION NOT NULL,
  fees          DOUBLE PRECISION NOT NULL DEFAULT 0,
  realized_pnl  DOUBLE PRECISION,
  executed_at   TEXT NOT NULL,
  source        TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_trades_account ON trades(account_id, executed_at DESC);

CREATE TABLE IF NOT EXISTS analytics_runs (
  id            TEXT PRIMARY KEY,
  kind          TEXT NOT NULL,
  input_hash    TEXT NOT NULL,
  model_version TEXT NOT NULL,
  params        TEXT NOT NULL,
  result        TEXT NOT NULL,
  created_by    TEXT,
  created_at    TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS entitlement_records (
  id         TEXT PRIMARY KEY,
  provider   TEXT NOT NULL,
  dataset    TEXT NOT NULL,
  level      TEXT NOT NULL,
  user_id    TEXT REFERENCES users(id) ON DELETE CASCADE,
  granted_at TEXT NOT NULL,
  expires_at TEXT,
  notes      TEXT
);
