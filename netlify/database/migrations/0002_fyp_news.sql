ALTER TABLE news_sources ADD COLUMN IF NOT EXISTS format TEXT NOT NULL DEFAULT 'rss';
ALTER TABLE news_sources ADD COLUMN IF NOT EXISTS interval_seconds INTEGER NOT NULL DEFAULT 900;
ALTER TABLE news_sources ADD COLUMN IF NOT EXISTS attribution TEXT;
ALTER TABLE news_sources ADD COLUMN IF NOT EXISTS license TEXT;
ALTER TABLE news_sources ADD COLUMN IF NOT EXISTS region_hint TEXT;
ALTER TABLE news_sources ADD COLUMN IF NOT EXISTS category_hint TEXT;
ALTER TABLE news_sources ADD COLUMN IF NOT EXISTS official INTEGER NOT NULL DEFAULT 0;
ALTER TABLE news_sources ADD COLUMN IF NOT EXISTS last_polled_at TEXT;
ALTER TABLE news_sources ADD COLUMN IF NOT EXISTS last_success_at TEXT;
ALTER TABLE news_sources ADD COLUMN IF NOT EXISTS last_error TEXT;
ALTER TABLE news_sources ADD COLUMN IF NOT EXISTS consecutive_failures INTEGER NOT NULL DEFAULT 0;
ALTER TABLE news_sources ADD COLUMN IF NOT EXISTS etag TEXT;
ALTER TABLE news_sources ADD COLUMN IF NOT EXISTS last_modified TEXT;
ALTER TABLE news_sources ADD COLUMN IF NOT EXISTS next_attempt_at TEXT;
ALTER TABLE news_sources ADD COLUMN IF NOT EXISTS items_total INTEGER NOT NULL DEFAULT 0;
ALTER TABLE news_sources ADD COLUMN IF NOT EXISTS last_latency_ms INTEGER;
ALTER TABLE news_sources ADD COLUMN IF NOT EXISTS last_item_count INTEGER NOT NULL DEFAULT 0;
ALTER TABLE news_sources ADD COLUMN IF NOT EXISTS unavailable_reason TEXT;

CREATE TABLE IF NOT EXISTS news_stories (
  id                TEXT PRIMARY KEY,
  provider_key      TEXT NOT NULL,
  provider_item_id  TEXT NOT NULL,
  source_name       TEXT NOT NULL,
  source_homepage   TEXT,
  url               TEXT,
  canonical_url     TEXT,
  title             TEXT NOT NULL,
  summary           TEXT,
  published_at      TEXT,
  published_known   INTEGER NOT NULL DEFAULT 0,
  source_updated_at TEXT,
  received_at       TEXT NOT NULL,
  ingested_at       TEXT NOT NULL,
  updated_at        TEXT NOT NULL,
  country           TEXT,
  region            TEXT NOT NULL,
  category          TEXT NOT NULL,
  subcategory       TEXT,
  entities          TEXT NOT NULL DEFAULT '[]',
  keywords          TEXT NOT NULL DEFAULT '[]',
  asset_classes     TEXT NOT NULL DEFAULT '[]',
  symbols           TEXT NOT NULL DEFAULT '[]',
  urgency           INTEGER NOT NULL,
  relevance         INTEGER NOT NULL,
  priority          TEXT NOT NULL,
  verification      TEXT NOT NULL,
  source_count      INTEGER NOT NULL DEFAULT 1,
  sources           TEXT NOT NULL,
  cluster_id        TEXT NOT NULL,
  status            TEXT NOT NULL DEFAULT 'new',
  is_breaking       INTEGER NOT NULL DEFAULT 0,
  content_hash      TEXT NOT NULL,
  dedupe_key        TEXT NOT NULL,
  attribution       TEXT,
  license           TEXT,
  is_fixture        INTEGER NOT NULL DEFAULT 0,
  UNIQUE(provider_key, provider_item_id),
  UNIQUE(dedupe_key)
);
CREATE INDEX IF NOT EXISTS idx_news_stories_received ON news_stories(received_at DESC);
CREATE INDEX IF NOT EXISTS idx_news_stories_published ON news_stories(published_at DESC);
CREATE INDEX IF NOT EXISTS idx_news_stories_category ON news_stories(category, received_at DESC);
CREATE INDEX IF NOT EXISTS idx_news_stories_region ON news_stories(region, received_at DESC);
CREATE INDEX IF NOT EXISTS idx_news_stories_cluster ON news_stories(cluster_id);
CREATE INDEX IF NOT EXISTS idx_news_stories_priority ON news_stories(priority, received_at DESC);
CREATE INDEX IF NOT EXISTS idx_news_stories_canonical ON news_stories(canonical_url);

CREATE TABLE IF NOT EXISTS news_story_impacts (
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  story_id          TEXT NOT NULL,
  symbol            TEXT NOT NULL,
  asset_class       TEXT NOT NULL,
  direction         TEXT NOT NULL,
  mechanism         TEXT NOT NULL,
  confidence        DOUBLE PRECISION NOT NULL,
  is_interpretation INTEGER NOT NULL DEFAULT 1,
  UNIQUE(story_id, symbol)
);
CREATE INDEX IF NOT EXISTS idx_news_impacts_story ON news_story_impacts(story_id);
CREATE INDEX IF NOT EXISTS idx_news_impacts_symbol ON news_story_impacts(symbol);

CREATE TABLE IF NOT EXISTS news_saved (
  user_id  TEXT NOT NULL,
  story_id TEXT NOT NULL,
  saved_at TEXT NOT NULL,
  PRIMARY KEY (user_id, story_id)
);

CREATE TABLE IF NOT EXISTS news_settings (
  key        TEXT PRIMARY KEY,
  value      TEXT NOT NULL,
  updated_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS news_ingest_runs (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  started_at      TEXT NOT NULL,
  finished_at     TEXT NOT NULL,
  providers_tried INTEGER NOT NULL,
  items_seen      INTEGER NOT NULL,
  inserted        INTEGER NOT NULL,
  merged          INTEGER NOT NULL,
  clustered       INTEGER NOT NULL,
  errors          INTEGER NOT NULL,
  detail          TEXT NOT NULL DEFAULT '[]'
);
CREATE INDEX IF NOT EXISTS idx_news_ingest_runs_finished ON news_ingest_runs(finished_at DESC);
